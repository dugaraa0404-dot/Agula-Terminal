import fs from 'fs';
import { geoNaturalEarth1, geoPath, geoArea, geoCentroid } from 'd3-geo';
import { feature } from 'topojson-client';
const topo = JSON.parse(fs.readFileSync('node_modules/world-atlas/countries-110m.json'));
const fc = feature(topo, topo.objects.countries);
fc.features = fc.features.filter(f => f.properties.name !== 'Antarctica');
const W = 960, H = 470;
const proj = geoNaturalEarth1().fitExtent([[4, 4], [W - 4, H - 4]], fc);
const path = geoPath(proj).digits(1);
const out = [];
for (const f of fc.features) {
  let d = path(f); if (!d) continue;
  // centroid of the largest polygon (so France/USA dots sit on the mainland)
  let geom = f.geometry, big = geom;
  if (geom.type === 'MultiPolygon') { let best = -1; for (const poly of geom.coordinates) { const g = { type: 'Polygon', coordinates: poly }; const a = geoArea(g); if (a > best) { best = a; big = g; } } }
  const [cx, cy] = geoPath(proj).centroid(big), [lon, lat] = geoCentroid(big);
  out.push({ id: f.id || '', n: f.properties.name, d, c: [Math.round(cx * 10) / 10, Math.round(cy * 10) / 10], ll: [Math.round(lon * 10) / 10, Math.round(lat * 10) / 10] });
}
const k = proj.scale(), [tx, ty] = proj.translate();
// sanity: JS reimplementation of naturalEarth1 must match d3
const raw = (l, p) => { const p2 = p * p, p4 = p2 * p2; return [l * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4))), p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4)))]; };
for (const [lon, lat] of [[0, 0], [106.9, 47.9], [-74, 40.7], [151.2, -33.9]]) { const a = proj([lon, lat]); const r = raw(lon * Math.PI / 180, lat * Math.PI / 180); const b = [tx + k * r[0], ty - k * r[1]]; if (Math.abs(a[0] - b[0]) > 0.01 || Math.abs(a[1] - b[1]) > 0.01) throw new Error('projection mismatch ' + a + ' ' + b); }
const js = `/* World map for GEO: Natural Earth 1:110m countries (public domain, via world-atlas), Natural Earth projection. Generated by dev/geo/build_geo.mjs. */\n'use strict';\nconst GEOWORLD = ${JSON.stringify({ w: W, h: H, k: +k.toFixed(4), tx: +tx.toFixed(3), ty: +ty.toFixed(3), countries: out })};\n`;
fs.writeFileSync('geo_world.js', js);
console.log(out.length, 'countries', (js.length / 1024).toFixed(0) + ' KB', 'k', k, tx, ty);
console.log(out.map(o => o.n).join('|'));
