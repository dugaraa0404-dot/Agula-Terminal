"""Build agula.py: the whole Agula Terminal in one Python file.

    python dev/build.py            -> agula.py (server + embedded page)
    python dev/build.py --html     -> also writes agula_terminal.html for inspection

Takes the server source (dev/agula_server.py), bundles the front-end in dev/src/
(JavaScript modules, CSS, body) into one HTML page, and embeds that page in the
server as PAGE_HTML. Re-run after editing anything in dev/.
"""
import pathlib

import sys

DEV = pathlib.Path(__file__).resolve().parent
ROOT = DEV.parent
SRC = DEV / "src"
MARK = "PAGE_HTML = None  # @@EMBEDDED_PAGE@@"
ORDER = ["util.js", "quant.js", "dcf_engine.js", "data.js", "chartkit.js", "app.js",
         "screens_core.js", "screens_dcf.js", "screens_more.js", "screens_news.js"]

BOOT = """
/* ---------------- boot ---------------- */
(function boot() {
  APP.init();
  if (document.fonts && document.fonts.ready) document.fonts.ready.then(() => { CK.resetColors(); const s = APP.state.screen; if (s) APP.open(s); });
})();
"""

HEAD = """<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>Agula Terminal</title>
<meta name="description" content="Agula Terminal: a keyboard-first market terminal with live quotes, charts, DCF models with Excel export, option chains, portfolio risk, the Treasury curve, FX, a screener and an economic calendar.">
<!-- API base URL. Empty = same origin as this page (the normal case when agula.py serves it). -->
<meta name="agula-api" content="">
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600;700&family=IBM+Plex+Sans+Condensed:wght@400;500;600;700&display=swap">
<style>
:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}img{max-width:100%}[hidden]{display:none!important}
"""


def build_html() -> str:
    js = "\n".join((SRC / f).read_text(encoding="utf-8") for f in ORDER)
    css = (SRC / "style.css").read_text(encoding="utf-8")
    body = (SRC / "body.html").read_text(encoding="utf-8")
    html = ("<!doctype html>\n<html lang=\"en\">\n<head>\n" + HEAD + css + "\n</style>\n</head>\n<body>\n"
            + body + "\n<script>\n'use strict';\n" + js + BOOT + "</script>\n</body>\n</html>\n")
    return html


def build() -> pathlib.Path:
    html = build_html()
    if "'''" in html or html.endswith("\\"):
        raise SystemExit("page contains a triple quote or ends with a backslash; cannot embed as a raw string")
    server = (DEV / "agula_server.py").read_text(encoding="utf-8")
    if server.count(MARK) != 1:
        raise SystemExit(f"marker not found in agula_server.py: {MARK}")
    code = server.replace(MARK, "PAGE_HTML = r'''" + html + "'''")
    code = code.replace('"""\nAgula Terminal\n==============\n',
                        '"""\nAgula Terminal\n==============\n(This file is generated by dev/build.py. To change it, edit dev/ and rebuild.)\n', 1)
    out = ROOT / "agula.py"
    out.write_text(code, encoding="utf-8")
    compile(code, str(out), "exec")            # fail the build on a syntax error
    if "--html" in sys.argv:
        (ROOT / "agula_terminal.html").write_text(html, encoding="utf-8")
    return out


if __name__ == "__main__":
    out = build()
    print(f"wrote {out.name} ({out.stat().st_size // 1024} KB)")
